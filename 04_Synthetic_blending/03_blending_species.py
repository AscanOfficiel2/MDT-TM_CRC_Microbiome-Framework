centroids = {g: by_group[g].mean(axis=0) for g in classes}

records, entropy_records, mdt_rows = [], [], []

# ============================================================
# MDT simulation
# ============================================================

for rec, donors in transitions.items():
    for don in donors:

        Xr, Xd = by_group[rec], by_group[don]
        mu_r, mu_d = centroids[rec], centroids[don]
        don_idx = np.where(classes == don)[0][0]

        probs_by_alpha = []

        for a in alphas:
            cnt, ents = 0, []

            for _ in range(n_pairs):
                xr = Xr[rng.integers(len(Xr))]
                xd = Xd[rng.integers(len(Xd))]
                x_mix = mix_samples(xr, xd, a).reshape(1, -1)

                proba = model.predict_proba(x_mix)[0]
                cnt += (np.argmax(proba) == don_idx)
                ents.append(entropy(proba, base=2))

            p = cnt / n_pairs
            lo, hi = wilson_ci(cnt, n_pairs)

            records.append({
                "Mode": "sample",
                "Recipient": rec,
                "Donor": don,
                "alpha": a,
                "P_donor": p,
                "CI_low": lo,
                "CI_high": hi
            })

            entropy_records.append({
                "Recipient": rec,
                "Donor": don,
                "alpha": a,
                "Entropy_mean": np.mean(ents),
                "Entropy_sd": np.std(ents)
            })

            probs_by_alpha.append(p)

        hit = [a for a, p in zip(alphas, probs_by_alpha) if p >= prob_thresh]
        mdt = hit[0] if hit else np.nan
        mdt_rows.append({"Recipient": rec, "Donor": don, "MDT": mdt})

        # centroid
        for a in alphas:
            x_mix = mix_centroids(mu_r, mu_d, a).reshape(1, -1)
            y_hat = model.predict(x_mix)[0]
            p = float(y_hat == don)

            records.append({
                "Mode": "centroid",
                "Recipient": rec,
                "Donor": don,
                "alpha": a,
                "P_donor": p,
                "CI_low": p,
                "CI_high": p
            })

