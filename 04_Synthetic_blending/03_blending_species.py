# ============================================================
# (★) Driving species at MDT − ε using directional perturbation
# SVM-compatible, publication-ready
# ============================================================

delta = 0.05            # small CLR perturbation
n_driver_samples = 50   # blended samples at tipping region
epsilon = 0.05          # one alpha step before MDT

GOLD_TRANSITION = "#d4af37"  # GOLD for Adenoma → Cancer

for _, r in mdt_df.dropna().iterrows():

    rec = r["Recipient"]
    don = r["Donor"]
    mdt = r["MDT"]

    # Evaluate just BEFORE the tipping point
    a = max(0.0, mdt - epsilon)

    print(f"\n▶ Driving species for {rec} → {don} at α = {a:.2f}")

    Xr = by_group[rec]
    Xd = by_group[don]
    don_idx = np.where(classes == don)[0][0]

    # ---- Build blended samples ----
    blends = []
    for _ in range(n_driver_samples):
        xr = Xr[rng.integers(len(Xr))]
        xd = Xd[rng.integers(len(Xd))]
        blends.append((1 - a) * xr + a * xd)

    blends = np.array(blends)

    # ---- Baseline donor probability ----
    base_probs = model.predict_proba(blends)[:, don_idx]

    effects = []

    # ---- Directional perturbation ----
    for j, sp in enumerate(species):
        X_plus  = blends.copy()
        X_minus = blends.copy()

        X_plus[:, j]  += delta
        X_minus[:, j] -= delta

        p_plus  = model.predict_proba(X_plus)[:, don_idx]
        p_minus = model.predict_proba(X_minus)[:, don_idx]

        # Mean absolute probability shift
        delta_p = np.mean(np.abs(p_plus - p_minus))
        effects.append(delta_p)

    driver_df = pd.DataFrame({
        "Species": species,
        "Delta_P": effects
    }).sort_values("Delta_P", ascending=False)

    # ---- Save full table ----
    driver_df.to_csv(
        f"CRC_MDT_DrivingSpecies_{rec}_to_{don}_directional.csv",
        index=False
    )

    # ---- Select bar color ----
    if rec == "Adenoma" and don == "Cancer":
        bar_color = GOLD_TRANSITION   # GOLD
    else:
        bar_color = palette[don]

    # ---- Plot top drivers ----
    top = driver_df.head(20)

    fig, ax = plt.subplots(figsize=(6,7))
    ax.barh(
        top["Species"],
        top["Delta_P"],
        color=bar_color,
        edgecolor="black"
    )

    ax.set_xlabel("Δ P(donor) under ±δ perturbation")
    ax.set_title(
        f"Driving species at tipping point\n({rec} → {don}, α = {a:.2f})"
    )
    ax.invert_yaxis()
    thicken_spines(ax)

