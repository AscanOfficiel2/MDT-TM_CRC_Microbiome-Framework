# ============================================================
# CRC Multiclass ML Pipeline — FINAL, COMPLETE, SUBMISSION-READY
# Benchmarking + Nested CV (ALL MODELS)
# ROC + PR + Calibration + Youden + Confusion Matrices
# Classes: Healthy / Adenoma / Cancer
# ============================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import StratifiedKFold, train_test_split, GridSearchCV
from sklearn.preprocessing import label_binarize
from sklearn.metrics import (
    accuracy_score, balanced_accuracy_score, f1_score,
    matthews_corrcoef, confusion_matrix,
    roc_curve, roc_auc_score,
    precision_recall_curve, average_precision_score
)
from sklearn.calibration import calibration_curve

from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.svm import SVC

sns.set_style("white")

# ============================================================
# Helper: enforce thick borders on all plots
# ============================================================

def thicken_spines(ax, lw=1.8):
    for spine in ax.spines.values():
        spine.set_visible(True)
        spine.set_linewidth(lw)
        spine.set_color("black")

# ============================================================
# 1. Load and align data
# ============================================================

tpm = pd.read_csv("TPM_clr_batch_corrected_v2.csv", index_col=0)
meta = pd.read_csv("CRC_metadata_aligned_bact.csv")

common = tpm.index.intersection(meta["Sample_ID"])
tpm = tpm.loc[common]
meta = meta[meta["Sample_ID"].isin(common)].reset_index(drop=True)
tpm = tpm.loc[meta["Sample_ID"]]

X = tpm.values
y = meta["Group"].values
classes = np.unique(y)

print("Class distribution:")
print(pd.Series(y).value_counts())

# ============================================================
# 2. Train / hold-out split (HOLD-OUT NEVER USED IN CV)
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=42
)

# ============================================================
# 3. Candidate models (UNTUNED)
# ============================================================

base_models = {
    "DecisionTree": DecisionTreeClassifier(class_weight="balanced", random_state=42),
    "RandomForest": RandomForestClassifier(class_weight="balanced", random_state=42, n_jobs=-1),
    "LogisticRegression": LogisticRegression(max_iter=5000, class_weight="balanced"),
    "SVM": SVC(kernel="rbf", probability=True, class_weight="balanced"),
    "GradientBoosting": GradientBoostingClassifier(random_state=42)
}

# ============================================================
# 4. OUTER CV BENCHMARKING (ALL METRICS)
# ============================================================

outer_cv = StratifiedKFold(n_splits=10, shuffle=True, random_state=42)
records = []

for name, model in base_models.items():
    for tr_idx, te_idx in outer_cv.split(X_train, y_train):
        X_tr, X_te = X_train[tr_idx], X_train[te_idx]
        y_tr, y_te = y_train[tr_idx], y_train[te_idx]

        model.fit(X_tr, y_tr)
        y_pred = model.predict(X_te)

        records.append({
            "Model": name,
            "Accuracy": accuracy_score(y_te, y_pred),
            "BalancedAccuracy": balanced_accuracy_score(y_te, y_pred),
            "F1_macro": f1_score(y_te, y_pred, average="macro"),
            "MCC": matthews_corrcoef(y_te, y_pred),
            "MacroMCC": np.mean([
                matthews_corrcoef((y_te == c), (y_pred == c))
                for c in classes
            ])
        })

benchmark_df = pd.DataFrame(records)
benchmark_summary = benchmark_df.groupby("Model").agg(["mean", "std"])
benchmark_summary.to_csv("CRC_Benchmarking_PreNestedCV.csv")

# ============================================================
# 4B. BENCHMARKING PLOT (ALL METRICS)
# ============================================================

model_colors = {
    "DecisionTree": "#1f77b4",
    "RandomForest": "#2ca02c",
    "LogisticRegression": "#ff7f0e",
    "SVM": "#d62728",
    "GradientBoosting": "#9467bd"
}

plot_df = benchmark_summary.copy()
plot_df.columns = ["_".join(c) for c in plot_df.columns]
plot_df = plot_df.reset_index()

metrics = sorted({c.replace("_mean", "") for c in plot_df.columns if c.endswith("_mean")})

fig, axes = plt.subplots(1, len(metrics), figsize=(5 * len(metrics), 5), sharey=True)
if len(metrics) == 1:
    axes = [axes]

for ax, metric in zip(axes, metrics):
    for _, row in plot_df.iterrows():
        ax.errorbar(
            row[f"{metric}_mean"], row["Model"],
            xerr=row[f"{metric}_std"],
            fmt="o", capsize=4, markersize=7,
            color=model_colors[row["Model"]]
        )
    ax.set_title(metric.replace("_", " "), weight="bold")
    ax.set_xlabel("Mean ± SD")
    ax.grid(False)
    thicken_spines(ax)

axes[0].set_ylabel("Model")
plt.suptitle("Model Benchmarking (10-fold Stratified CV)", weight="bold", y=1.05)
plt.tight_layout()
plt.savefig("Figure_Model_Benchmarking_AllMetrics.png", dpi=600, bbox_inches="tight")
plt.show()

# ============================================================
# 5. MODEL SELECTION (COMPOSITE SCORE)
# ============================================================

ranking = benchmark_summary.copy()
ranking["CompositeScore"] = (
    ranking[("BalancedAccuracy", "mean")] +
    ranking[("MacroMCC", "mean")] +
    ranking[("Accuracy", "mean")]
)

best_model_name = ranking["CompositeScore"].idxmax()
print("\n🏆 Selected model for tuning:", best_model_name)

# ============================================================
# 6. NESTED CV HYPERPARAMETER TUNING (ALL MODELS SUPPORTED)
# ============================================================

param_grids = {
    "DecisionTree": {"max_depth": [None, 5, 10], "min_samples_leaf": [1, 3, 5]},
    "RandomForest": {"n_estimators": [300, 500], "max_depth": [None, 10, 20]},
    "LogisticRegression": {"C": [0.1, 1, 10]},
    "SVM": {"C": [0.1, 1, 10], "gamma": ["scale", 0.01, 0.1]},
    "GradientBoosting": {"n_estimators": [100, 300], "learning_rate": [0.05, 0.1]}
}

grid = GridSearchCV(
    base_models[best_model_name],
    param_grids[best_model_name],
    cv=StratifiedKFold(5, shuffle=True, random_state=42),
    scoring="balanced_accuracy",
    n_jobs=-1
)

grid.fit(X_train, y_train)
best_model = grid.best_estimator_

pd.DataFrame([grid.best_params_]).to_csv("CRC_BestModel_Params.csv", index=False)

# ============================================================
# 7. FINAL HOLD-OUT EVALUATION
# ============================================================

best_model.fit(X_train, y_train)
y_pred = best_model.predict(X_test)
y_proba = best_model.predict_proba(X_test)

# ============================================================
# 8. ROC CURVES (MULTICLASS OvR)
# ============================================================

y_bin = label_binarize(y_test, classes=classes)

plt.figure(figsize=(6, 5))
ax = plt.gca()

for i, cls in enumerate(classes):
    fpr, tpr, _ = roc_curve(y_bin[:, i], y_proba[:, i])
    auc = roc_auc_score(y_bin[:, i], y_proba[:, i])
    ax.plot(fpr, tpr, lw=2, label=f"{cls} (AUC={auc:.2f})")

ax.plot([0, 1], [0, 1], "k--", lw=1.5)
ax.set_xlabel("False Positive Rate")
ax.set_ylabel("True Positive Rate")
ax.set_title("ROC Curves (Hold-out)")
ax.legend(frameon=False)
thicken_spines(ax)

plt.tight_layout()
plt.savefig("Figure_ROC_Curves.png", dpi=600)
plt.show()

# ============================================================
# 9. PRECISION–RECALL CURVES
# ============================================================

plt.figure(figsize=(6, 5))
ax = plt.gca()

for i, cls in enumerate(classes):
    prec, rec, _ = precision_recall_curve(y_bin[:, i], y_proba[:, i])
    ap = average_precision_score(y_bin[:, i], y_proba[:, i])
    ax.plot(rec, prec, lw=2, label=f"{cls} (AP={ap:.2f})")

ax.set_xlabel("Recall")
ax.set_ylabel("Precision")
ax.set_title("Precision–Recall Curves (Hold-out)")
ax.legend(frameon=False)
thicken_spines(ax)

plt.tight_layout()
plt.savefig("Figure_PR_Curves.png", dpi=600)
plt.show()

# ============================================================
# 10. CALIBRATION CURVES
# ============================================================

plt.figure(figsize=(6, 5))
ax = plt.gca()

for i, cls in enumerate(classes):
    frac_pos, mean_pred = calibration_curve(y_bin[:, i], y_proba[:, i], n_bins=10)
    ax.plot(mean_pred, frac_pos, marker="o", lw=2, label=cls)

ax.plot([0, 1], [0, 1], "k--", lw=1.5)
ax.set_xlabel("Mean Predicted Probability")
ax.set_ylabel("Observed Frequency")
ax.set_title("Calibration Curves (Hold-out)")
ax.legend(frameon=False)
thicken_spines(ax)

plt.tight_layout()
plt.savefig("Figure_Calibration_Curves.png", dpi=600)
plt.show()

# ============================================================
# 11. CONFUSION MATRICES (DEFAULT THRESHOLD)
# ============================================================

cm = confusion_matrix(y_test, y_pred, labels=classes)
cm_norm = cm / cm.sum(axis=1, keepdims=True)

fig, axes = plt.subplots(1, 2, figsize=(10, 4))

sns.heatmap(cm, annot=True, fmt="d", cmap="Blues",
            xticklabels=classes, yticklabels=classes,
            cbar=False, ax=axes[0])
axes[0].set_title("Confusion Matrix (Counts)")
axes[0].set_xlabel("Predicted")
axes[0].set_ylabel("True")
thicken_spines(axes[0])

sns.heatmap(cm_norm, annot=True, fmt=".2f", cmap="Blues",
            xticklabels=classes, yticklabels=classes,
            cbar=True, ax=axes[1])
axes[1].set_title("Confusion Matrix (Normalized)")
axes[1].set_xlabel("Predicted")
axes[1].set_ylabel("")
thicken_spines(axes[1])

plt.tight_layout()
plt.savefig("Figure_ConfusionMatrices.png", dpi=600, bbox_inches="tight")
plt.show()

# ============================================================
# 12. YOUDEN’S THRESHOLD (Cancer vs Rest)
# ============================================================

cancer_idx = np.where(classes == "Cancer")[0][0]
y_true_bin = (y_test == "Cancer").astype(int)
y_score = y_proba[:, cancer_idx]

fpr, tpr, thresholds = roc_curve(y_true_bin, y_score)
youden = tpr - fpr
best_idx = np.argmax(youden)
youden_threshold = thresholds[best_idx]

pd.DataFrame({
    "Youden_threshold": [youden_threshold],
    "TPR": [tpr[best_idx]],
    "FPR": [fpr[best_idx]]
}).to_csv("Youden_Threshold_Cancer_vs_Rest.csv", index=False)

# ============================================================
# 12A. ROC WITH YOUDEN POINT
# ============================================================

plt.figure(figsize=(6, 5))
ax = plt.gca()

ax.plot(fpr, tpr, lw=2, label="ROC")
ax.scatter(fpr[best_idx], tpr[best_idx], color="red", s=80,
           label=f"Youden (t={youden_threshold:.2f})")
ax.plot([0, 1], [0, 1], "k--", lw=1.5)

ax.set_xlabel("False Positive Rate")
ax.set_ylabel("True Positive Rate")
ax.set_title("ROC with Youden Threshold (Cancer vs Rest)")
ax.legend(frameon=False)
thicken_spines(ax)

plt.tight_layout()
plt.savefig("Figure_ROC_Youden.png", dpi=600)
plt.show()

# ============================================================
# 12B. CONFUSION MATRIX AT YOUDEN THRESHOLD
# ============================================================

y_pred_youden = (y_score >= youden_threshold).astype(int)
cm_youden = confusion_matrix(y_true_bin, y_pred_youden)
cm_youden_norm = cm_youden / cm_youden.sum(axis=1, keepdims=True)

fig, axes = plt.subplots(1, 2, figsize=(10, 4))

sns.heatmap(cm_youden, annot=True, fmt="d", cmap="Blues",
            xticklabels=["Pred Non-Cancer", "Pred Cancer"],
            yticklabels=["True Non-Cancer", "True Cancer"],
            cbar=False, ax=axes[0])
axes[0].set_title("Youden Threshold — Counts")
axes[0].set_xlabel("Predicted")
axes[0].set_ylabel("True")
thicken_spines(axes[0])

sns.heatmap(cm_youden_norm, annot=True, fmt=".2f", cmap="Blues",
            xticklabels=["Pred Non-Cancer", "Pred Cancer"],
            yticklabels=["True Non-Cancer", "True Cancer"],
            cbar=True, ax=axes[1])
axes[1].set_title("Youden Threshold — Normalized")
axes[1].set_xlabel("Predicted")
axes[1].set_ylabel("")
thicken_spines(axes[1])

plt.tight_layout()
plt.savefig("Figure_ConfusionMatrix_Youden.png", dpi=600, bbox_inches="tight")
plt.show()

