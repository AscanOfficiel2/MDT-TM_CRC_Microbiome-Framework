# ============================================================
# MDT Proximity Assignment — Mechanistic & Reproducible
# CRC Microbiome — Observer Reconstruction + MDT State
# ============================================================

import pandas as pd
import numpy as np

from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC

# ------------------------------------------------------------
# 0. Reproducibility
# ------------------------------------------------------------

RANDOM_STATE = 42
np.random.seed(RANDOM_STATE)

# ------------------------------------------------------------
# 1. Load Data
# ------------------------------------------------------------

X = pd.read_csv("TPM_clr_batch_corrected_v2.csv", index_col=0)
meta = pd.read_csv("CRC_metadata_aligned_bact.csv")

# ------------------------------------------------------------
# 2. Align Samples
# ------------------------------------------------------------

common_samples = X.index.intersection(meta["Sample_ID"])
X = X.loc[common_samples]
meta = meta[meta["Sample_ID"].isin(common_samples)].reset_index(drop=True)
X = X.loc[meta["Sample_ID"]]

y = meta["Group"].values

print("Samples:", X.shape[0])
print("Features:", X.shape[1])
print("\nClass distribution:")
print(pd.Series(y).value_counts())

# ------------------------------------------------------------
# 3. Train Fixed Observer Model (Full Dataset)
# ------------------------------------------------------------
# NOTE:
# This is intentional. For MDT state-space reconstruction,
# the observer must be trained on the full dataset.
# 80/20 splitting is only for benchmarking, not for state definition.

observer = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler()),
    ("svm", SVC(
        kernel="rbf",
        C=10,
        gamma="scale",
        probability=True,
        class_weight="balanced",
        random_state=RANDOM_STATE
    ))
])

observer.fit(X, y)

print("\nObserver model trained successfully.")

# ------------------------------------------------------------
# 4. Compute Class Probabilities
# ------------------------------------------------------------

proba = observer.predict_proba(X)
classes = observer.classes_

proba_df = pd.DataFrame(proba, columns=classes, index=X.index)

for cls in classes:
    meta[f"P_{cls}"] = proba_df[cls].values

print("\nProbability summary (Cancer class):")
print(meta["P_Cancer"].describe())

# ------------------------------------------------------------
# 5. Mechanistic MDT Stratification
# ------------------------------------------------------------
# MDT threshold derived from MDT-TM simulations

MDT_THRESHOLD = 0.8
TRANSITION_LOWER = 0.7

print("\nUsing fixed mechanistic thresholds:")
print("Transition lower bound:", TRANSITION_LOWER)
print("MDT (collapse threshold):", MDT_THRESHOLD)

meta["MDT_state"] = "pre_MDT"

meta.loc[
    (meta["P_Cancer"] >= TRANSITION_LOWER) &
    (meta["P_Cancer"] < MDT_THRESHOLD),
    "MDT_state"
] = "transition"

meta.loc[
    meta["P_Cancer"] >= MDT_THRESHOLD,
    "MDT_state"
] = "post_MDT"

meta["MDT_state"] = pd.Categorical(
    meta["MDT_state"],
    categories=["pre_MDT", "transition", "post_MDT"],
    ordered=True
)

# ------------------------------------------------------------
# 6. Diagnostics
# ------------------------------------------------------------

print("\nMDT state distribution:")
print(meta["MDT_state"].value_counts())

print("\nCross-tab with clinical group:")
print(pd.crosstab(meta["Group"], meta["MDT_state"]))

# ------------------------------------------------------------
# 7. Save Outputs
# ------------------------------------------------------------

meta.to_csv("CRC_metadata_with_MDT_state.csv", index=False)
proba_df.to_csv("CRC_sample_class_probabilities.csv")

thresholds = pd.DataFrame({
    "TRANSITION_LOWER": [TRANSITION_LOWER],
    "MDT_THRESHOLD": [MDT_THRESHOLD]
})
thresholds.to_csv("MDT_thresholds_used.csv", index=False)

print("\nMDT proximity assignment complete.")
print("Saved:")
print("- CRC_metadata_with_MDT_state.csv")
print("- CRC_sample_class_probabilities.csv")
print("- MDT_thresholds_used.csv")