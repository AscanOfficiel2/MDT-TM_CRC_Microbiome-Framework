# ============================================================
# Permutation Feature Importance with NaN-safe Pipeline
# CRC Microbiome | Tuned SVM (RBF)
# ============================================================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.metrics import balanced_accuracy_score, matthews_corrcoef
from sklearn.svm import SVC

sns.set_style("white")

# ============================================================
# 1. Load and align data
# ============================================================

tpm = pd.read_csv("TPM_clr_batch_corrected_v2.csv", index_col=0)
meta = pd.read_csv("CRC_metadata_aligned_bact.csv")

common = tpm.index.intersection(meta["Sample_ID"])
tpm = tpm.loc[common]
meta = meta[meta["Sample_ID"].isin(common)].reset_index(drop=True)
tpm = tpm.loc[meta["Sample_ID"]]

X = tpm.values
species = tpm.columns.tolist()
y = meta["Group"].values
classes = np.unique(y)

print("Class distribution:")
print(pd.Series(y).value_counts())

# ============================================================
# 2. Train / hold-out split
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.2,
    stratify=y,
    random_state=42
)

# ============================================================
# 3. Build NaN-safe pipeline (IMPUTER + SVM)
# ============================================================

pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("svm", SVC(
        kernel="rbf",
        C=10,
        gamma="scale",
        probability=True,
        class_weight="balanced",
        random_state=42
    ))
])

pipeline.fit(X_train, y_train)

# ============================================================
# 4. GLOBAL permutation importance
# ============================================================

print("\nComputing GLOBAL permutation importance...")

perm_global = permutation_importance(
    pipeline,
    X_test,
    y_test,
    n_repeats=20,
    scoring="balanced_accuracy",
    random_state=42,
    n_jobs=-1
)

global_df = pd.DataFrame({
    "Species": species,
    "Importance": perm_global.importances_mean,
    "SD": perm_global.importances_std
}).sort_values("Importance", ascending=False)

global_df.to_csv("FeatureImportance_Global_SVM.csv", index=False)

# ---- Plot: Global importance (mean ± SD) ----
topN = 25
plot_df = global_df.head(topN)

plt.figure(figsize=(6, 7))
plt.barh(
    plot_df["Species"],
    plot_df["Importance"],
    xerr=plot_df["SD"],
    capsize=3,
    color="steelblue",
    edgecolor="black"
)

plt.xlabel("Permutation Importance (Δ Balanced Accuracy)")
plt.title("Global Feature Importance (SVM)")
plt.gca().invert_yaxis()
plt.tight_layout()
plt.savefig("Figure_Global_FeatureImportance_SVM.tiff", dpi=600)
plt.show()

# ============================================================
# 5. CLASS-SPECIFIC permutation importance (OvR)
# ============================================================

def class_specific_mcc(y_true, y_pred, positive_class):
    return matthews_corrcoef(
        (y_true == positive_class).astype(int),
        (y_pred == positive_class).astype(int)
    )

for cls in classes:
    print(f"\nComputing importance for {cls} vs Rest")

    def scorer(estimator, X, y):
        y_hat = estimator.predict(X)
        return class_specific_mcc(y, y_hat, cls)

    perm = permutation_importance(
        pipeline,
        X_test,
        y_test,
        n_repeats=20,
        scoring=scorer,
        random_state=42,
        n_jobs=-1
    )

    df_cls = pd.DataFrame({
        "Species": species,
        "Importance": perm.importances_mean,
        "SD": perm.importances_std
    }).sort_values("Importance", ascending=False)

    df_cls.to_csv(f"FeatureImportance_{cls}_OvR_SVM.csv", index=False)

    # ---- Plot ----
    plot_df = df_cls.head(topN)

    plt.figure(figsize=(6, 7))
    plt.barh(
        plot_df["Species"],
        plot_df["Importance"],
        xerr=plot_df["SD"],
        capsize=3,
        color="darkorange",
        edgecolor="black"
    )

    plt.xlabel("Permutation Importance (Δ MCC)")
    plt.title(f"{cls} vs Rest — Feature Importance")
    plt.gca().invert_yaxis()
    plt.tight_layout()
    plt.savefig(f"Figure_FeatureImportance_{cls}_OvR_SVM.tiff", dpi=600)
    plt.show()

print("\n✔ Feature importance analysis completed successfully.")